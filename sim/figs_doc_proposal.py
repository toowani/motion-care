"""Infographic figures for docs/proposal.md (plain SVG, helpers from figs_tables.py).

    python3 sim/figs_doc_proposal.py      # writes docs/img/doc_proposal_<n>.svg

Markup inside text: **bold**, ‹D› ‹τ› ‹P› ‹m› ‹I› ‹ρ› = italic variable in the formula colour.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import crave_style as cs
import figs_tables as ft
from figs_tables import Svg, tw, wrap, INK, MUTED, FOOT, BLUE, BAND, LINE, CARD

VARS = {"D": ft.V_D, "τ": ft.V_TAU, "P": ft.V_P, "m": ft.V_M, "I": ft.V_I, "ρ": INK}
TOK = re.compile(r"(\*\*|‹[DτPmIρ]›)")
SZ, LH = 14, 21


def segs(line, bold):
    out = []
    for t in TOK.split(line):
        if not t:
            continue
        if t == "**":
            bold = not bold
        elif t.startswith("‹"):
            out.append((t[1], VARS[t[1]], "var"))
        elif bold:
            out.append((t, INK, "bold"))
        else:
            out.append(t)
    return out, bold


def draw_lines(s, x, y, lines, size=SZ, lh=LH, fill=MUTED):
    bold = False
    for ln in lines:
        sg, bold = segs(ln, bold)
        s.rich(x, y, sg, size, fill=fill)
        y += lh
    return y


def para_lines(p, width, size=SZ):
    """-> (level, wrapped lines); '- ' prefix = sub bullet, '> ' = plain (no bullet)."""
    p = p.replace("`", "")
    lvl = 1
    if p.startswith("- "):
        lvl, p = 2, p[2:]
    elif p.startswith("> "):
        lvl, p = 0, p[2:]
    off = {0: 0, 1: 14, 2: 32}[lvl]
    return lvl, wrap(p, size, width - off), off


def block_height(b, w):
    h = 22 if not b.get("head") else 56
    for p in b["paras"]:
        lvl, ls, off = para_lines(p, w - 36)
        h += len(ls) * LH + 5
    return h + 8


def draw_block(s, b, x, y, w, h):
    s.card(x, y, w, h)
    yy = y + 28
    if b.get("head"):
        s.icon(b.get("icon", "doc"), x + 30, y + 30, BLUE, BAND, 16)
        s.text(x + 56, y + 37, b["head"], 17, INK, "start", 800)
        yy = y + 68
    for p in b["paras"]:
        lvl, ls, off = para_lines(p, w - 36)
        if lvl:
            s.circle(x + 22 + (off - 14), yy - 5, 2.5, FOOT)
        yy = draw_lines(s, x + 22 + off, yy, ls) + 5


def blocks_section(s, y, blocks, ncol=1, gap=14):
    cw = (904 - gap * (ncol - 1)) / ncol
    for i in range(0, len(blocks), ncol):
        row = blocks[i:i + ncol]
        h = max(block_height(b, cw) for b in row)
        for j, b in enumerate(row):
            draw_block(s, b, 28 + j * (cw + gap), y, cw, h)
        y += h + gap
    return y


def table_section(s, y, cols, rows, size=13.5):
    """cols: [(header, width)], widths sum to 904. rows: list of cell strings."""
    xs = [28]
    for _, w in cols:
        xs.append(xs[-1] + w)
    s.rect(28, y, 904, 34, BAND, 10)
    for (hd, w), x in zip(cols, xs):
        s.text(x + 12, y + 22, hd, 13.5, BLUE, "start", 700)
    y += 40
    for r in rows:
        wr = [wrap(c, size, w - 24) for c, (_, w) in zip(r, cols)]
        h = max(len(w_) for w_ in wr) * 20 + 18
        s.card(28, y, 904, h, rx=10)
        for k, (lines, x) in enumerate(zip(wr, xs)):
            bold = k == 0
            yy = y + 24
            for ln in lines:
                if bold:
                    s.text(x + 12, yy, ln.replace("**", ""), size, INK, "start", 700)
                    yy += 20
                else:
                    yy = draw_lines(s, x + 12, yy, [ln], size, 20)
        for x in xs[1:-1]:
            s.line(x, y + 8, x, y + h - 8, LINE)
        y += h + 8
    return y


def make(name, title, items):
    """items: ('b', blocks, ncol) | ('t', cols, rows). Two passes: measure on a scratch Svg."""
    def run(s):
        y = 28
        for it in items:
            if it[0] == "b":
                y = blocks_section(s, y, it[1], it[2] if len(it) > 2 else 1)
            else:
                y = table_section(s, y, it[1], it[2]) + 6
        return y - 14 + 28
    tmp = Svg(960, 100)
    H = run(tmp)
    s = Svg(960, H)
    run(s)
    s.save(name, title)


def B(icon, head, *paras):
    return {"icon": icon, "head": head, "paras": list(paras)}


def N(*paras):
    return {"paras": list(paras)}


